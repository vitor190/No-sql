/**
 * Modelo de dados do chat em tempo real, guardado no Space como SpaceDocuments.
 *
 *   Usuario   (id, nome, status, ultimoAcesso)
 *   Sala      (id, nome, descricao, criadaPor, criadaEm)
 *   Mensagem  (id, salaId, autorId, texto, enviadaEm, editada, editadaEm)
 *
 * Mensagem usa salaId como ROUTING PROPERTY: num Space particionado, todas as
 * mensagens de uma mesma sala ficam na mesma partição. Ler o histórico de uma
 * sala é então uma consulta a uma única partição em memória (muito rápido).
 */
import type { TypeDescriptor } from "../gigaspaces/SpaceClient.js";

export const TYPES = {
  usuario: "Usuario",
  sala: "Sala",
  mensagem: "Mensagem",
} as const;

export interface Usuario {
  [k: string]: unknown;
  id: string;
  nome: string;
  status: "online" | "offline";
  ultimoAcesso: number; // epoch ms
}

export interface Sala {
  [k: string]: unknown;
  id: string;
  nome: string;
  descricao: string;
  criadaPor: string;
  criadaEm: number;
}

export interface Mensagem {
  [k: string]: unknown;
  id: string;
  salaId: string;
  autorId: string;
  texto: string;
  enviadaEm: number;
  editada: boolean;
  editadaEm: number; // 0 = nunca editada
}

