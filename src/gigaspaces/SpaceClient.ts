/**
 * Cliente TypeScript para o REST Service do GigaSpaces (Space REST API).
 *
 * O GigaSpaces é um "tuple store": os dados vivem num espaço de memória
 * compartilhado (o Space) e são manipulados por operações no estilo Linda/JavaSpaces:
 *
 *   write  -> coloca uma entrada (tupla) no Space           (C do CRUD)
 *   read   -> lê uma cópia da entrada; ela continua lá      (R do CRUD)
 *   write  -> com um id já existente, substitui a entrada    (U do CRUD, UPDATE_OR_WRITE)
 *   take   -> lê E remove a entrada do Space                 (D do CRUD)
 *
 * Endpoints usados (REST Service do GigaSpaces; testado no XAP 16.1.0):
 *   PUT    /{Type}/_introduce_type   registra o tipo (schema do SpaceDocument)
 *   POST   /{Type}                   write / writeMultiple (upsert pelo id)
 *   GET    /{Type}/{id}              readById
 *   GET    /{Type}?query=..&max=..   readMultiple por consulta SQL-like
 *   GET    /{Type}/count             count
 *   DELETE /{Type}/{id}              takeById
 *   DELETE /{Type}?query=..&max=..   takeMultiple
 *
 * As respostas têm o formato { "status": "success", "data": ... }, e cada entrada
 * vem como { typeName, version, properties: { ...campos } } (veja unwrap()).
 */

export type SpaceDocument = Record<string, unknown>;

/** Nomes de tipos aceitos pelo REST Service em fixedProperties[].propertyType */
export type PropertyType =
  | "string" | "int32" | "int64" | "double" | "float" | "number"
  | "boolean" | "datetime" | "array" | "set" | "sortedset" | "object";

export type IndexType = "NONE" | "EQUAL" | "ORDERED" | "EQUAL_AND_ORDERED";

export interface FixedProperty {
  propertyName: string;
  propertyType: PropertyType;
  indexType?: IndexType;
}

/** Corpo de PUT /{Type}/_introduce_type */
export interface TypeDescriptor {
  idProperty: { propertyName: string; autoGenerated?: boolean; indexType?: IndexType };
  routingProperty?: { propertyName: string; indexType?: IndexType };
  fixedProperties?: FixedProperty[];
  fifoSupport?: "OFF" | "OPERATION" | "ALL" | "DEFAULT";
  supportsDynamicProperties?: boolean;
  supportsOptimisticLocking?: boolean;
}

/** Registro de cada operação feita no Space (exibido na interface e na demo). */
export interface SpaceOperation {
  at: number;
  op: "introduceType" | "write" | "read" | "readMultiple" | "count" | "take" | "takeMultiple";
  http: string;
  type: string;
  detail?: string;
  ok: boolean;
  ms: number;
  /** O que foi gravado (write) ou o que voltou do Space (read/take/consulta). */
  dados?: unknown;
  /** Quantidade de entradas envolvidas (quando é uma lista). */
  total?: number;
  /** Mensagem de erro, quando a operação falha. */
  erro?: string;
}

export class SpaceError extends Error {
  constructor(message: string, public readonly httpStatus?: number, public readonly body?: unknown) {
    super(message);
    this.name = "SpaceError";
  }
}

interface RestResponse<T> {
  status?: string;
  data?: T;
  error?: unknown;
  message?: string;
}

export class SpaceClient {
  private listeners: Array<(op: SpaceOperation) => void> = [];

  constructor(private readonly baseUrl: string) {}

  /** Permite observar cada operação (usado no painel "operações no Space"). */
  onOperation(listener: (op: SpaceOperation) => void): void {
    this.listeners.push(listener);
  }

  // ------------------------------------------------------------------ schema

  /** Registra um tipo no Space. Se o tipo já existir, não é erro. */
  async introduceType(type: string, descriptor: TypeDescriptor): Promise<"created" | "exists"> {
    try {
      await this.request("introduceType", "PUT", `/${enc(type)}/_introduce_type`, type, descriptor, undefined, (_s, b) => ALREADY.test(JSON.stringify(b)));
      return "created";
    } catch (e) {
      if (e instanceof SpaceError && ALREADY.test(JSON.stringify(e.body ?? e.message))) {
        return "exists";
      }
      throw e;
    }
  }

  // ------------------------------------------------------------------ C / U

  /**
   * write: coloca uma ou mais entradas no Space.
   * No GigaSpaces o modificador padrão é UPDATE_OR_WRITE: se já existe uma entrada
   * com o mesmo id, ela é substituída (é assim que fazemos o UPDATE).
   */
  async write(type: string, docs: SpaceDocument | SpaceDocument[]): Promise<void> {
    const n = Array.isArray(docs) ? docs.length : 1;
    await this.request("write", "POST", `/${enc(type)}`, type, docs, `${n} entrada(s)`);
  }

  /**
   * Atualização parcial: read -> merge -> write (o write com o mesmo id
   * substitui a entrada inteira no Space). Retorna a entrada nova, ou null se não existir.
   */
  async update<T extends SpaceDocument>(type: string, id: string, patch: Partial<T>): Promise<T | null> {
    const current = await this.readById<T>(type, id);
    if (!current) return null;
    const updated = { ...current, ...patch } as T;
    await this.write(type, updated);
    return updated;
  }

  // ------------------------------------------------------------------ R

  /** read por id. Retorna null se a entrada não existir. */
  async readById<T extends SpaceDocument>(type: string, id: string): Promise<T | null> {
    try {
      return emptyToNull(await this.request<T>("read", "GET", `/${enc(type)}/${enc(id)}`, type, undefined, `id=${id}`, is404));
    } catch (e) {
      if (e instanceof SpaceError && e.httpStatus === 404) return null;
      throw e;
    }
  }

  /** readMultiple por consulta SQL-like (ex.: "salaId='geral' AND editada=true"). */
  async readMultiple<T extends SpaceDocument>(type: string, query?: string, max = 1000): Promise<T[]> {
    const qs = buildQuery(query, max);
    try {
      const data = await this.request<T[]>("readMultiple", "GET", `/${enc(type)}${qs}`, type, undefined, query ?? "(todos)", is404);
      return Array.isArray(data) ? data : [];
    } catch (e) {
      // O REST Service responde 404 quando nenhuma entrada casa com a consulta.
      if (e instanceof SpaceError && e.httpStatus === 404) return [];
      throw e;
    }
  }

  async count(type: string): Promise<number> {
    const data = await this.request<number>("count", "GET", `/${enc(type)}/count`, type);
    return Number(data ?? 0);
  }

  // ------------------------------------------------------------------ D

  /** take por id: remove a entrada do Space e devolve o que foi removido. */
  async takeById<T extends SpaceDocument>(type: string, id: string): Promise<T | null> {
    try {
      return emptyToNull(await this.request<T>("take", "DELETE", `/${enc(type)}/${enc(id)}`, type, undefined, `id=${id}`, is404));
    } catch (e) {
      if (e instanceof SpaceError && e.httpStatus === 404) return null;
      throw e;
    }
  }

  /**
   * Remove TODAS as entradas de um tipo (usado pelo setup para limpar o Space).
   * O REST Service ignora um DELETE sem consulta, por isso usamos "id IS NOT NULL".
   */
  async takeAll(type: string): Promise<number> {
    return (await this.takeMultiple(type, "id IS NOT NULL", 100_000)).length;
  }

  /** takeMultiple: remove todas as entradas que casam com a consulta. */
  async takeMultiple<T extends SpaceDocument>(type: string, query: string, max = 10000): Promise<T[]> {
    try {
      const data = await this.request<T[]>("takeMultiple", "DELETE", `/${enc(type)}${buildQuery(query, max)}`, type, undefined, query, is404);
      return Array.isArray(data) ? data : [];
    } catch (e) {
      if (e instanceof SpaceError && e.httpStatus === 404) return [];
      throw e;
    }
  }

  /** Verifica se o REST Service está acessível. */
  async ping(type: string): Promise<boolean> {
    try {
      await this.count(type);
      return true;
    } catch {
      return false;
    }
  }

  // ------------------------------------------------------------------ HTTP

  private async request<T>(
    op: SpaceOperation["op"],
    method: string,
    path: string,
    type: string,
    body?: unknown,
    detail?: string,
    okIf?: (status: number, body: unknown) => boolean,
  ): Promise<T> {
    const started = Date.now();
    const http = `${method} ${decodeURIComponent(path)}`;
    let ok = false;
    let result: unknown;
    let erro: string | undefined;
    try {
      let res: Response;
      try {
        res = await fetch(this.baseUrl + path, {
          method,
          headers: body !== undefined ? { "Content-Type": "application/json", Accept: "application/json" } : { Accept: "application/json" },
          body: body !== undefined ? JSON.stringify(body) : undefined,
          signal: AbortSignal.timeout(10_000),
        });
      } catch (e) {
        throw new SpaceError(
          `Não foi possível conectar ao GigaSpaces em ${this.baseUrl} (${(e as Error).message}). ` +
            `O REST Service (PU chat-rest) está implantado? Veja o README.`,
        );
      }

      const text = await res.text();
      let json: RestResponse<T> | undefined;
      try {
        json = text ? (JSON.parse(text) as RestResponse<T>) : undefined;
      } catch {
        json = undefined;
      }

      if (!res.ok && okIf?.(res.status, json ?? text)) {
        // Resposta "esperada" (ex.: 404 = não existe). Não é falha da operação.
        ok = true;
        detail = `${detail ?? ""} → ${res.status === 404 ? "não encontrado" : "já existia"}`.trim();
        throw new SpaceError(`expected ${res.status}`, res.status, json ?? text);
      }
      if (!res.ok) {
        const msg = json?.message ?? (typeof json?.error === "string" ? json.error : undefined) ?? (text.slice(0, 300) || res.statusText);
        throw new SpaceError(`GigaSpaces respondeu ${res.status} em ${http}: ${msg}`, res.status, json ?? text);
      }
      if (json && json.status && json.status !== "success") {
        throw new SpaceError(`GigaSpaces retornou status "${json.status}" em ${http}`, res.status, json);
      }
      ok = true;
      result = unwrap(json?.data);
      return result as T;
    } catch (e) {
      if (!ok) erro = (e as Error).message;
      throw e;
    } finally {
      const dados = method === "POST" ? body : result;
      const entry: SpaceOperation = {
        at: started, op, http, type, detail, ok, ms: Date.now() - started,
        dados, total: Array.isArray(dados) ? dados.length : undefined, erro,
      };
      for (const l of this.listeners) l(entry);
    }
  }
}

/**
 * O REST Service do GigaSpaces devolve cada entrada no formato
 *   { "typeName": "Sala", "version": 1, "transient": false, "properties": { id, nome, ... } }
 * Aqui extraímos só os campos (properties), para o resto do código trabalhar
 * com objetos simples. Valores que já vêm "soltos" (simulador, count) passam direto.
 */
function unwrap(data: unknown): unknown {
  if (Array.isArray(data)) return data.map(unwrap);
  if (data && typeof data === "object") {
    const d = data as Record<string, unknown>;
    if (typeof d.typeName === "string" && d.properties && typeof d.properties === "object") {
      return d.properties;
    }
  }
  return data;
}

/** O GigaSpaces real responde 200 com data = {} quando o id não existe (o simulador responde 404). */
function emptyToNull<T>(doc: T | null | undefined): T | null {
  if (!doc || (typeof doc === "object" && Object.keys(doc as object).length === 0)) return null;
  return doc;
}

const ALREADY = /already|registered|exist/i;
const is404 = (status: number) => status === 404;

function enc(s: string): string {
  return encodeURIComponent(s);
}

function buildQuery(query: string | undefined, max: number): string {
  const params = new URLSearchParams();
  if (query) params.set("query", query);
  params.set("max", String(max));
  return "?" + params.toString();
}

/**
 * Monta um literal de texto seguro para as consultas SQL-like do Space.
 * A API REST não aceita parâmetros (?), então recusamos aspas simples
 * para evitar "SQL injection" na consulta.
 */
export function sqlText(value: string): string {
  if (value.includes("'")) throw new SpaceError(`Valor inválido para consulta: ${value}`);
  return `'${value}'`;
}
